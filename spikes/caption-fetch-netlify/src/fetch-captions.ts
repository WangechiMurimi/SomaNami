/**
 * Fetches YouTube captions the way `youtube-transcript-api` 1.x does (watch
 * page -> Innertube player -> timedtext), so a result from Netlify can be
 * compared one-to-one with the local Python spike in `../caption-fetch`.
 */

const WATCH_URL = 'https://www.youtube.com/watch?v='
const PLAYER_URL = 'https://www.youtube.com/youtubei/v1/player?key='
// The web client's caption URLs need a proof-of-origin token; the Android
// client's usually don't, which is why the Python library uses it too.
const INNERTUBE_CONTEXT = {
  client: { clientName: 'ANDROID', clientVersion: '20.10.38' },
}
const LANGUAGE = 'en'
export const VIDEO_ID_PATTERN = /^[A-Za-z0-9_-]{11}$/

/** Failure names match the Python library's exceptions so the two tables line up. */
export type CaptionErrorName =
  | 'IpBlocked'
  | 'RequestBlocked'
  | 'PoTokenRequired'
  | 'TranscriptsDisabled'
  | 'NoTranscriptFound'
  | 'VideoUnavailable'
  | 'AgeRestricted'
  | 'VideoUnplayable'
  | 'YouTubeDataUnparsable'
  | 'Timeout'
  | 'NetworkError'

/** Errors that mean YouTube refused this host, not that the video lacks captions. */
const BLOCKING_ERRORS: ReadonlySet<CaptionErrorName> = new Set([
  'IpBlocked',
  'RequestBlocked',
  'PoTokenRequired',
])

export class CaptionError extends Error {
  readonly name: CaptionErrorName

  constructor(name: CaptionErrorName, detail: string) {
    super(detail)
    this.name = name
  }
}

export interface Snippet {
  text: string
  start: number
  duration: number
}

export interface Transcript {
  language: string
  autoGenerated: boolean
  snippets: Snippet[]
}

export type CaptionResult =
  | {
      video_id: string
      ok: true
      snippets: number
      auto_generated: boolean
      language: string
      first_line: string | null
      ms: number
    }
  | {
      video_id: string
      ok: false
      error: CaptionErrorName
      blocked: boolean
      detail: string
      ms: number
    }

interface CaptionTrack {
  baseUrl: string
  languageCode: string
  kind?: string
}

type Fetch = typeof fetch

export interface FetchOptions {
  fetch?: Fetch
  /** Per-request budget; the whole function must finish inside Netlify's limit. */
  timeoutMs?: number
}

/** Fetches the English transcript for one video, throwing `CaptionError` on any failure. */
export async function fetchTranscript(
  videoId: string,
  { fetch: doFetch = fetch, timeoutMs = 8000 }: FetchOptions = {},
): Promise<Transcript> {
  const request = async (url: string, init: RequestInit = {}) => {
    try {
      return await doFetch(url, {
        ...init,
        headers: { 'Accept-Language': 'en-US', ...init.headers },
        signal: AbortSignal.timeout(timeoutMs),
      })
    } catch (error) {
      const timedOut =
        error instanceof DOMException && error.name === 'TimeoutError'
      throw new CaptionError(
        timedOut ? 'Timeout' : 'NetworkError',
        timedOut ? `No response within ${timeoutMs} ms` : String(error),
      )
    }
  }

  const html = await fetchWatchPage(videoId, request)
  const apiKey = extractApiKey(html)

  const playerResponse = await request(PLAYER_URL + apiKey, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ context: INNERTUBE_CONTEXT, videoId }),
  })
  if (playerResponse.status === 429) {
    throw new CaptionError('IpBlocked', 'Player request returned HTTP 429')
  }
  if (!playerResponse.ok) {
    throw new CaptionError(
      'YouTubeDataUnparsable',
      `Player request returned HTTP ${playerResponse.status}`,
    )
  }

  const track = pickTrack(readCaptionTracks(await playerResponse.json()))
  const url = track.baseUrl.replace('&fmt=srv3', '')
  if (url.includes('&exp=xpe')) {
    throw new CaptionError('PoTokenRequired', 'Caption URL requires a PO token')
  }

  const captionResponse = await request(url)
  if (captionResponse.status === 429) {
    throw new CaptionError('IpBlocked', 'Caption request returned HTTP 429')
  }
  const xml = await captionResponse.text()
  if (!captionResponse.ok || xml.trim() === '') {
    // An empty 200 is how YouTube answers a caption URL it won't serve to this client.
    throw new CaptionError(
      'RequestBlocked',
      `Caption request returned HTTP ${captionResponse.status} with ${xml.length} bytes`,
    )
  }

  return {
    language: track.languageCode,
    autoGenerated: track.kind === 'asr',
    snippets: parseTimedText(xml),
  }
}

type Request = (url: string, init?: RequestInit) => Promise<Response>

async function fetchWatchPage(
  videoId: string,
  request: Request,
): Promise<string> {
  const url = WATCH_URL + videoId
  let html = await readPage(await request(url))

  // EU hosts get a consent interstitial instead of the page; accept it once.
  if (html.includes('action="https://consent.youtube.com/s"')) {
    const value = /name="v" value="(.*?)"/.exec(html)?.[1]
    if (!value) {
      throw new CaptionError(
        'YouTubeDataUnparsable',
        'Consent page without a token',
      )
    }
    html = await readPage(
      await request(url, { headers: { Cookie: `CONSENT=YES+${value}` } }),
    )
  }
  return html
}

async function readPage(response: Response): Promise<string> {
  if (response.status === 429) {
    throw new CaptionError('IpBlocked', 'Watch page returned HTTP 429')
  }
  return response.text()
}

/** Pulls the Innertube key out of a watch page; a captcha page means this IP is blocked. */
export function extractApiKey(html: string): string {
  const key = /"INNERTUBE_API_KEY":\s*"([a-zA-Z0-9_-]+)"/.exec(html)?.[1]
  if (key) return key
  if (html.includes('class="g-recaptcha"')) {
    throw new CaptionError('IpBlocked', 'Watch page served a captcha')
  }
  throw new CaptionError(
    'YouTubeDataUnparsable',
    'No INNERTUBE_API_KEY in watch page',
  )
}

interface PlayerResponse {
  playabilityStatus?: { status?: string; reason?: string }
  captions?: {
    playerCaptionsTracklistRenderer?: { captionTracks?: CaptionTrack[] }
  }
}

/** Reads caption tracks from a player response, mapping playability failures to errors. */
export function readCaptionTracks(data: unknown): CaptionTrack[] {
  const { playabilityStatus, captions } = (data ?? {}) as PlayerResponse
  const status = playabilityStatus?.status
  const reason = playabilityStatus?.reason ?? ''

  if (status && status !== 'OK') {
    if (status === 'LOGIN_REQUIRED' && /not a bot/i.test(reason)) {
      throw new CaptionError('RequestBlocked', reason)
    }
    if (status === 'LOGIN_REQUIRED' && /inappropriate/i.test(reason)) {
      throw new CaptionError('AgeRestricted', reason)
    }
    if (status === 'ERROR' && /unavailable/i.test(reason)) {
      throw new CaptionError('VideoUnavailable', reason)
    }
    throw new CaptionError('VideoUnplayable', `${status}: ${reason}`.trim())
  }

  const tracks = captions?.playerCaptionsTracklistRenderer?.captionTracks
  if (!tracks || tracks.length === 0) {
    throw new CaptionError('TranscriptsDisabled', 'Video has no caption tracks')
  }
  return tracks
}

/** Prefers creator captions over auto-generated ones, as the Python library does. */
export function pickTrack(tracks: readonly CaptionTrack[]): CaptionTrack {
  const english = tracks.filter((track) => track.languageCode === LANGUAGE)
  const track =
    english.find((t) => t.kind !== 'asr') ??
    english.find((t) => t.kind === 'asr')
  if (!track) {
    const available = tracks.map((t) => t.languageCode).join(', ')
    throw new CaptionError(
      'NoTranscriptFound',
      `No English track (have: ${available})`,
    )
  }
  return track
}

const ENTITIES: Record<string, string> = {
  amp: '&',
  lt: '<',
  gt: '>',
  quot: '"',
  apos: "'",
  nbsp: ' ',
}

function decodeEntities(text: string): string {
  return text.replace(
    /&(#x[0-9a-f]+|#\d+|[a-z]+);/gi,
    (match, entity: string) => {
      if (entity[0] === '#') {
        const hex = entity[1] === 'x' || entity[1] === 'X'
        return String.fromCodePoint(
          parseInt(entity.slice(hex ? 2 : 1), hex ? 16 : 10),
        )
      }
      return ENTITIES[entity.toLowerCase()] ?? match
    },
  )
}

/** Parses timedtext XML into snippets, dropping markup and empty lines. */
export function parseTimedText(xml: string): Snippet[] {
  const snippets: Snippet[] = []
  for (const [, attributes, body] of xml.matchAll(
    /<text\b([^>]*)>([\s\S]*?)<\/text>/g,
  )) {
    // Caption bodies are entity-encoded once more, so markup appears only after decoding.
    const text = decodeEntities(decodeEntities(body!).replace(/<[^>]*>/g, ''))
      .replace(/\s+/g, ' ')
      .trim()
    if (!text) continue
    snippets.push({
      text,
      start: Number(/start="([\d.]+)"/.exec(attributes!)?.[1] ?? 0),
      duration: Number(/dur="([\d.]+)"/.exec(attributes!)?.[1] ?? 0),
    })
  }
  return snippets
}

/** Runs one video and reports it in the same shape as the Python spike's `test_video`. */
export async function testVideo(
  videoId: string,
  options: FetchOptions = {},
): Promise<CaptionResult> {
  const started = performance.now()
  const ms = () => Math.round(performance.now() - started)
  try {
    const transcript = await fetchTranscript(videoId, options)
    return {
      video_id: videoId,
      ok: true,
      snippets: transcript.snippets.length,
      auto_generated: transcript.autoGenerated,
      language: transcript.language,
      first_line: transcript.snippets[0]?.text ?? null,
      ms: ms(),
    }
  } catch (error) {
    // Record every failure type rather than crash: the failure mix is the finding.
    const known = error instanceof CaptionError
    const name: CaptionErrorName = known ? error.name : 'YouTubeDataUnparsable'
    return {
      video_id: videoId,
      ok: false,
      error: name,
      blocked: BLOCKING_ERRORS.has(name),
      detail: String(known ? error.message : error).slice(0, 300),
      ms: ms(),
    }
  }
}
